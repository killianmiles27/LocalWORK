import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { resolve } from "node:path";
import { createServer } from "vite";
const root = resolve(import.meta.dirname, "../..");
process.env.PLAYWRIGHT_BROWSERS_PATH = resolve(root, "vendor/browsers");
const { chromium } = createRequire(resolve(root, "vendor/playwright/package.json"))("playwright-core");
const server = await createServer({ root, server: { host: "127.0.0.1", port: 0 }, clearScreen: false });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 900, height: 850 } });
  const errors = []; page.on("pageerror", e => errors.push(String(e)));
  await page.goto(`${server.resolvedUrls.local[0]}scripts/tests/cloud-fixture.html`);
  const picker = page.getByRole("combobox", { name: "Reply location" });
  await picker.waitFor(); assert.equal(await picker.isDisabled(), true);
  await page.getByRole("button", { name: "Add provider" }).click();
  await page.getByLabel("Name", { exact: true }).fill("Test provider");
  await page.getByLabel("API base URL").fill("https://example.test/v1");
  await page.getByLabel("API key").fill("test-secret");
  await page.getByRole("button", { name: "Save provider" }).click();
  await page.getByRole("button", { name: "Fetch models" }).click();
  await page.getByText("https://example.test/v1 · 1 models").waitFor();
  await page.getByRole("combobox", { name: "Routing", exact: true }).selectOption("manual");
  await page.waitForFunction(() => !document.querySelector('[aria-label="Reply location"]').disabled);
  await picker.selectOption("cloud:test:model-a");
  await page.waitForFunction(() => window.calls.some(c => c.cmd === "chat_route_set" && c.args.model === "cloud:test:model-a"));
  await page.getByRole("checkbox", { name: "Check cloud requests for personal data" }).check();
  await page.getByLabel("Try the filter locally").fill("Hello Alice");
  await page.getByRole("button", { name: "Test locally" }).click();
  await page.getByText("Hello [PERSON_1]", { exact: false }).waitFor();
  await page.getByRole("button", { name: "View last cloud request" }).click();
  await page.getByRole("button", { name: "Hide request" }).waitFor();
  await page.getByRole("combobox", { name: "Routing", exact: true }).selectOption("local");
  await page.waitForFunction(() => document.querySelector('[aria-label="Reply location"]').disabled);
  const calls = await page.evaluate(() => window.calls);
  assert.equal(calls.some(c => c.cmd === "gate_install" || c.cmd === "engine_install"), false);
  assert.deepEqual(errors, []);
  console.log("PASS cloud controls: local default, provider/key save, fetched model, manual picker, privacy test, sent request, local override; mocked IPC only");
} finally { await browser?.close(); await server.close(); }
