import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { createServer } from "vite";
const root = resolve(import.meta.dirname, "../..");
const reviewDir = resolve(root, ".audit-tools/model-picker-review");
await mkdir(reviewDir, { recursive: true });
process.env.PLAYWRIGHT_BROWSERS_PATH = resolve(root, "vendor/browsers");
const { chromium } = createRequire(resolve(root, "vendor/playwright/package.json"))("playwright-core");
const server = await createServer({ root, server: { host: "127.0.0.1", port: 0 }, clearScreen: false });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  const errors = []; page.on("pageerror", e => errors.push(String(e)));
  await page.goto(`${server.resolvedUrls.local[0]}scripts/tests/cloud-fixture.html`);
  await page.getByTestId("mode-switcher").waitFor();
  assert.equal(await page.getByLabel("Default cloud model").count(), 0, "Automatic should use enabled cloud choices without a separate default-model control");

  const chatgpt = page.locator('summary[aria-label="Choose ChatGPT models"]');
  await chatgpt.click();
  await page.screenshot({ path: resolve(reviewDir, "cloud-model-catalog.png"), fullPage: true });
  const luna = page.getByRole("checkbox", { name: "gpt-6-luna" });
  await luna.uncheck();
  await page.waitForFunction(() => document.querySelector('[data-testid="mode-switcher"]') && window.calls.some(c => c.cmd === "cloud_set" && c.args.key === "cloudVisibleModels"));
  await page.getByTestId("mode-switcher").click();
  const rootMenu = page.getByRole("menu", { name: "Choose model" });
  await rootMenu.waitFor();
  await rootMenu.getByRole("menuitemradio", { name: /gpt-6-luna/ }).waitFor({ state: "detached" });
  await rootMenu.getByRole("menuitemradio", { name: /gpt-6\.1-sol/ }).waitFor();
  await page.keyboard.press("Escape");

  await page.getByRole("button", { name: "Add provider" }).click();
  await page.getByLabel("Name", { exact: true }).fill("Test provider");
  await page.getByLabel("API base URL").fill("https://example.test/v1");
  await page.getByLabel("API key").fill("test-secret");
  await page.getByRole("button", { name: "Save provider" }).click();
  await page.getByRole("button", { name: "Fetch models" }).click();
  await page.getByText("https://example.test/v1 · 1 models").waitFor();
  await page.locator('summary[aria-label="Choose Test provider models"]').click();
  await page.getByRole("checkbox", { name: "model-a" }).uncheck();
  await page.getByTestId("mode-switcher").click();
  await page.getByRole("menu", { name: "Choose model" }).getByText("Cloud models").waitFor();
  await page.getByRole("menu", { name: "Choose model" }).getByRole("menuitemradio", { name: /model-a/ }).waitFor({ state: "detached" });
  await page.mouse.click(1050, 850);
  await page.getByRole("menu", { name: "Choose model" }).waitFor({ state: "detached" });

  await page.getByTestId("mode-switcher").click();
  const cloudMenu = page.getByRole("menu", { name: "Choose model" });
  await cloudMenu.getByText("Cloud models").waitFor();
  const visibleCloudText = await cloudMenu.innerText();
  assert.match(visibleCloudText, /gpt-6\.1-sol/, `selected ChatGPT catalog model should appear in the picker: ${visibleCloudText}`);
  await cloudMenu.getByRole("menuitemradio", { name: /gpt-6\.1-sol/ }).click();
  await page.waitForFunction(() => window.calls.some(c => c.cmd === "chat_route_set" && c.args.model === "cloud:chatgpt:gpt-6.1-sol"));
  await page.getByRole("button", { name: "Install privacy filter" }).click();
  const progress = page.getByRole("progressbar", { name: "Installing privacy filter" });
  await progress.waitFor();
  assert.equal(await progress.getAttribute("aria-valuenow"), null, "unknown download size should show indeterminate progress");
  await page.evaluate(() => window.emitTauri("download-progress", { id: "gate-install", done: 25, total: 100, rate: 10, state: "downloading", stage: "downloading", message: "Downloading privacy filter…" }));
  await page.getByText("25%", { exact: true }).waitFor();
  await page.evaluate(() => window.emitTauri("download-progress", { id: "gate-install", done: 100, total: 100, rate: 0, state: "extracting", stage: "extracting", message: "Extracting privacy filter…" }));
  await page.getByText("Extracting privacy filter…").waitFor();
  await page.evaluate(() => window.finishGateInstall("fixture extraction failure"));
  await page.getByText("fixture extraction failure").waitFor();
  assert.equal(await page.getByRole("progressbar", { name: "Installing privacy filter" }).count(), 0, "failed installs must stop showing active progress");

  await page.getByRole("button", { name: "Install privacy filter" }).click();
  await page.getByRole("progressbar", { name: "Installing privacy filter" }).waitFor();
  await page.evaluate(() => window.emitTauri("download-progress", { id: "gate-install", done: 80, total: 100, rate: 10, state: "downloading", stage: "downloading", message: "Downloading privacy filter…" }));
  await page.getByText("80%", { exact: true }).waitFor();
  await page.evaluate(() => window.emitTauri("download-progress", { id: "gate-install", done: 100, total: 100, rate: 0, state: "extracting", stage: "extracting", message: "Extracting privacy filter…" }));
  await page.getByText("Extracting privacy filter…").waitFor();
  await page.evaluate(() => window.finishGateInstall());
  await page.getByText("Privacy filter installed").waitFor();
  await page.getByRole("checkbox", { name: "Check cloud requests for personal data" }).check();
  await page.getByLabel("Try the filter locally").fill("Hello Alice");
  await page.getByRole("button", { name: "Test locally" }).click();
  await page.getByText("Hello [PERSON_1]", { exact: false }).waitFor();
  await page.getByTestId("mode-switcher").click();
  await page.getByRole("button", { name: "View last cloud request" }).click();
  await page.getByRole("button", { name: "Close" }).waitFor();

  await page.getByRole("combobox", { name: "Routing", exact: true }).selectOption("local");
  const calls = await page.evaluate(() => window.calls);
  assert.equal(calls.some(c => c.cmd === "chatgpt_login"), false, "fixture must not perform live subscription sign-in");
  assert.equal(calls.some(c => c.cmd === "engine_install"), false);
  assert.deepEqual(errors, []);
  console.log("PASS cloud controls: selected ChatGPT/provider models update picker, no default cloud selector, privacy progress/error flow, local override; mocked IPC only");
} finally { await browser?.close(); await server.close(); }
